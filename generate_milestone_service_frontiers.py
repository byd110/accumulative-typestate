#!/usr/bin/env python3
"""Emit tables checked by milestone_service_seeds.v; this generator is untrusted."""
from collections import deque

PATTERNS = (
    ("milestone", "tir", ("tir",)),
    ("service", "twcq", ("twcq", "tcwq", "tcqw", "ctwq", "ctqw", "cqtw")),
)


def word(w):
    return "[::" + ";".join(w) + "]"


def emit(name, letters, seeds):
    initial = frozenset((k, 0) for k in range(len(seeds)))
    states, representatives, numbers = [initial], [""], {initial: 0}
    queue, transitions = deque([initial]), []
    while queue:
        current = queue.popleft()
        row = []
        for event in letters:
            successor = set()
            for k, j in current:
                if event in seeds[k][:j]:
                    successor.add((k, j))
                if j < len(seeds[k]) and seeds[k][j] == event:
                    successor.add((k, j + 1))
            successor = frozenset(successor)
            if successor not in numbers:
                numbers[successor] = len(states)
                states.append(successor)
                representatives.append(representatives[numbers[current]] + event)
                queue.append(successor)
            row.append(numbers[successor])
        transitions.append(row)
    n = len(states)
    print(f"\nModule {name.title()}SeedTable.")
    print(f"Local Notation A := {name}_alphabet.")
    if name == "milestone":
        print("Local Notation t := (@None bool).\nLocal Notation i := (Some false).\nLocal Notation r := (Some true).")
        event_index = "if x is Some b then if b then 2 else 1 else 0"
    else:
        print("Local Notation t := (false,false).\nLocal Notation w := (false,true).\nLocal Notation c := (true,false).\nLocal Notation q := (true,true).")
        event_index = "if x.1 then if x.2 then 3 else 2 else if x.2 then 1 else 0"
    print(f"Definition seeds : seq (seq A) := {word(map(word, seeds))}.")
    print(f"Definition seed_state := Finite.clone 'I_{n} _.")
    print("Definition seed_index k : seed_state :=")
    print(f"  @Ordinal {n} (minn {n-1} k) (leq_ltn_trans (geq_minl _ _) (ltnSn _)).")
    print("Definition seed_rows : seq (seq nat) := [::")
    print(";\n".join("  " + word(map(str, row)) for row in transitions) + "].")
    dead = numbers[frozenset()]
    print("Definition seed_transition (s : seed_state) (x : A) :=")
    print(f"  seed_index (nth {dead} (nth [::] seed_rows (val s)) ({event_index})).")
    print("Definition seed_frontiers : seq (seq (state A)) := [::")
    fronts = []
    for frontier in states:
        pairs = sorted(set((seeds[k][:j][::-1], seeds[k][j:]) for k, j in frontier))
        fronts.append("  " + word(f"({word(p)},{word(s)})" for p, s in pairs))
    print(";\n".join(fronts) + "].")
    print("Definition seed_frontier (s : seed_state) := nth [::] seed_frontiers (val s).")
    print("Definition seed_dfa : dfa A :=")
    print("  {| dfa_state := seed_state; dfa_s := seed_index 0;")
    print("     dfa_fin := [set s | has (fun z : state A => z.2 == [::]) (seed_frontier s)];")
    print("     dfa_trans := seed_transition |}.")
    print(f"Definition seed_semantic (s : seed_state) : option {name}_state :=")
    print("  match val s with")
    for k, (frontier, rep) in enumerate(zip(states, representatives)):
        if frontier:
            flags = ",".join("true" if event in rep else "false" for event in letters)
            print(f"  | {k} => Some ({flags})")
    print("  | _ => None\n  end.")
    print(f"End {name.title()}SeedTable.")


def main():
    print("(* Generated by generate_milestone_service_frontiers.py; checked by Rocq. *)")
    print("From mathcomp Require Import all_ssreflect.")
    print("From RegLang Require Import dfa.")
    print("From Accumulation Require Import coverage_simulation milestone_service_patterns.")
    for pattern in PATTERNS:
        emit(*pattern)


if __name__ == "__main__":
    main()
